def _silent_run(dsn, s3log, bucket, srv, r):
    """The shell's silent-store arm (#1727 review): a 4-worker export, the fixture server
    stopped once a worker has PUT a part, the workers terminated, and their exit timed.
    Each wait slice times out, so the 60 s quiet limit ends a worker's abort; without
    WL_TIMEOUT the review saw all four alive at +92 s. No upload seen is a red too."""
    def run():
        try:
            with psycopg.connect(dsn, autocommit=True, connect_timeout=10) as conn:
                conn.execute(PART)
                conn.execute("SELECT pgcolumnar.parallel_export_parquet("
                             f"'es_parbig'::regclass, 's3://{BUCKET}/hs', 4)").fetchall()
        except psycopg.Error:
            pass

    shutil.rmtree(bucket / "hs", ignore_errors=True)
    open(s3log, "w").close()
    bg = threading.Thread(target=run)
    bg.start()
    wrote = "no"
    for _ in range(300):
        n = _logn(s3log, r"^PUT /pgc-bucket/hs/part-")
        if isinstance(n, int) and n >= 1:
            wrote = "yes"
            break
        time.sleep(0.1)
    srv.send_signal(signal.SIGSTOP)
    try:
        n_workers = _row(dsn, f"SELECT count(*) FROM pg_stat_activity WHERE {WORKERS}")
        _row(dsn, f"SELECT count(*) FROM (SELECT pg_terminate_backend(pid) FROM pg_stat_activity "
                  f"WHERE {WORKERS}) t")
        t0 = time.monotonic()
        left = n_workers
        for _ in range(90):
            left = _row(dsn, f"SELECT count(*) FROM pg_stat_activity WHERE {WORKERS}")
            if left == "0":
                break
            time.sleep(1)
        dt = int(time.monotonic() - t0)
    finally:
        srv.send_signal(signal.SIGCONT)
    with psycopg.connect(dsn, autocommit=True) as c:
        c.execute("SELECT pg_cancel_backend(pid) FROM pg_stat_activity "
                  "WHERE query LIKE '%parallel_export_parquet%' AND state = 'active' "
                  "AND pid <> pg_backend_pid()")
    bg.join(600)
    print(f"-- store silent: {n_workers} workers terminated, {left} left after {dt}s")
    if wrote != "yes":
        r["hs exit"] = "no upload seen"
    elif n_workers.isdigit() and int(n_workers) >= 1 and left == "0" and dt <= 75:
        r["hs exit"] = "bounded"
    else:
        r["hs exit"] = f"slow ({n_workers} workers, {left} left after {dt}s)"


def _part_set(dsn, value):
    """-> "accepted", or the message of the refusal, as the shell's part_set reads it."""
    try:
        with psycopg.connect(dsn, autocommit=True, connect_timeout=10) as conn:
            conn.execute(f"SET pgcolumnar.objstore_part_size = {value}")
    except psycopg.Error as exc:
        return exc.diag.message_primary or query_error(_message(exc))
    return "accepted"


def _staged_run(dsn, s3log, bucket, work):
    """#1812's chunk arm: about 500 MB staged, then the Arrow batch of one row with two
    400 MB values, at the 512 MiB part size. -> "rows|parts=N|identical" against a local
    export of the table."""
    with psycopg.connect(dsn, autocommit=True) as c:
        c.execute("CREATE TABLE es_staged (id int, a text, b text) USING pgcolumnar")
        c.execute("SELECT pgcolumnar.set_options('es_staged', stripe_row_limit => 1000)")
        c.execute("INSERT INTO es_staged SELECT g, repeat('y', 250000), '' FROM generate_series(1, 2000) g")
        c.execute("INSERT INTO es_staged VALUES (2001, repeat('z', 400000000), repeat('w', 400000000))")
    open(s3log, "w").close()
    remote, local = bucket / "staged.arrow", work / "staged-local.arrow"
    try:
        got = _row(dsn, f"SELECT pgcolumnar.export_arrow('es_staged', 's3://{BUCKET}/staged.arrow')",
                   setup=["SET statement_timeout = '900s'", "SET pgcolumnar.objstore_part_size = 536870912"])
        _row(dsn, f"SELECT pgcolumnar.export_arrow('es_staged', '{local}')")
        parts = _logn(s3log, r"^PUT /pgc-bucket/staged.arrow partNumber=")
        if remote.is_file() and local.is_file() and remote.read_bytes() == local.read_bytes():
            same = "identical"
        else:
            size = {p: (p.stat().st_size if p.is_file() else "missing") for p in (remote, local)}
            same = f"differs ({size[remote]} vs {size[local]} bytes)"
        return f"{got}|parts={parts}|{same}"
    finally:
        remote.unlink(missing_ok=True)
        local.unlink(missing_ok=True)
        with psycopg.connect(dsn, autocommit=True) as c:
            c.execute("DROP TABLE es_staged")

