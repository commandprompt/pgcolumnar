def _message(exc):
    return str(exc).splitlines()[0] if str(exc) else type(exc).__name__


def _wait_up(dsn):
    """Wait up to 15 s for the server, as the shell's readings do after a refusal."""
    for _ in range(30):
        try:
            with psycopg.connect(dsn, autocommit=True, connect_timeout=5) as conn:
                conn.execute("SELECT 1")
            return
        except psycopg.Error:
            time.sleep(0.5)


def _row(dsn, sql, setup=()):
    """-> the first row's columns joined by a space, or the failure as a query_error()."""
    _wait_up(dsn)
    try:
        with psycopg.connect(dsn, autocommit=True, connect_timeout=10) as conn:
            for s in setup:
                conn.execute(s)
            row = conn.execute(sql).fetchone()
    except psycopg.Error as exc:
        return query_error(_message(exc))
    if row is None:
        return query_error(f"no row from {sql}")
    return " ".join("" if v is None else str(v) for v in row)


def _set_hash(dsn, sql):
    """The port of pgc_set_hash: md5 of the rows' text, sorted."""
    return _row(dsn, "SELECT coalesce(md5(string_agg(t, chr(10) ORDER BY t)), 'EMPTY') "
                     f"FROM (SELECT _row::text AS t FROM ( {sql} ) _row) _s")


def _refusal(dsn, sql, phrase, label, setup=()):
    """-> "<SQLSTATE><label>" when `sql` raised with `phrase` in its message, the bare
    SQLSTATE when the message lacks it, or what happened instead."""
    _wait_up(dsn)
    try:
        with psycopg.connect(dsn, autocommit=True, connect_timeout=10) as conn:
            for s in setup:
                conn.execute(s)
            conn.execute(sql).fetchall()
    except psycopg.Error as exc:
        if not exc.sqlstate:
            return query_error(_message(exc))
        return exc.sqlstate + (label if phrase in str(exc) else "")
    return "no error"


def _refused_by(dsn, sql, setup=()):
    """-> "refused by the dispatcher" when `sql` raised the allow-list refusal itself,
    "refused by worker N" when the dispatcher re-raised a worker's error, or what
    happened instead."""
    _wait_up(dsn)
    try:
        with psycopg.connect(dsn, autocommit=True, connect_timeout=10) as conn:
            for s in setup:
                conn.execute(s)
            conn.execute(sql).fetchall()
    except psycopg.Error as exc:
        m = re.search(r"worker [0-9]+(?= failed)", str(exc))
        if m:
            return f"refused by {m.group(0)}"
        if "is not in pgcolumnar.objstore_allowed_endpoints" in str(exc):
            return "refused by the dispatcher"
        return f"not refused ({_message(exc)})"
    return "not refused (no error)"


def _logn(log, pattern):
    """-> how many request-log lines match `pattern` (grep -cE), or a query_error()."""
    try:
        lines = pathlib.Path(log).read_text(errors="replace").splitlines()
    except OSError as exc:
        return query_error(f"request log unreadable: {exc}")
    return sum(1 for line in lines if re.search(pattern, line))


def _open_uploads(work, pattern):
    """-> how many uploads the fixture server still holds open for keys matching `pattern`."""
    f = work / "__open_uploads__"
    if not f.is_file():
        return "0"
    return str(sum(1 for line in f.read_text(errors="replace").splitlines() if re.search(pattern, line)))


def _parts(d):
    """-> how many part-*.parquet objects are under `d` (0 when it does not exist)."""
    return sum(1 for p in d.iterdir() if re.search(r"part-.*\.parquet$", p.name)) if d.is_dir() else 0


def _system_list(dsn, alter, value):
    """Run an ALTER SYSTEM on the allow-list, reload, and wait up to 10 s for a new
    session to see `value`. -> what the last session saw, in brackets, so a reload
    that never lands shows."""
    with psycopg.connect(dsn, autocommit=True) as c:
        c.execute(alter)
        c.execute("SELECT pg_reload_conf()")
    for _ in range(50):
        seen = _row(dsn, "SELECT current_setting('pgcolumnar.objstore_allowed_endpoints')")
        if seen == value:
            break
        time.sleep(0.2)
    return f"[{seen}]"


def _pg_ctl(cluster, args, extra_env):
    """pg_ctl with an explicit environment: every AWS_* of this process removed, then
    `extra_env` added. Dropped to postgres when running as root, as the harness does."""
    unset = [a for k in os.environ if k.startswith("AWS_") for a in ("-u", k)]
    cmd = ["env"] + unset + [f"{k}={v}" for k, v in extra_env.items()] + \
          [os.path.join(cluster.bindir, "pg_ctl")] + args
    if os.geteuid() == 0:
        cmd = ["runuser", "-u", "postgres", "--"] + cmd
    return subprocess.run(cmd, capture_output=True, text=True)


def _restart(cluster, datadir, log, env):
    """Restart the private cluster with env and wait for it, as pg_restart_env does."""
    _pg_ctl(cluster, ["-D", str(datadir), "-m", "fast", "-w", "stop"], {})
    started = _pg_ctl(cluster, ["-D", str(datadir), "-l", log, "-w", "start"], env)
    for _ in range(30):
        if started.returncode == 0 and _row(cluster.dsn(), "SELECT 1") == "1":
            return
        time.sleep(0.5)
    raise RuntimeError(f"cluster did not come back after env restart: {started.stderr.strip()}")


def _cancel_run(dsn, s3log, bucket, r):
    """The shell's cancel arm: a 4-worker export of es_parbig in the background, cancelled
    once a worker has PUT a part."""
    out = {}

    def run():
        try:
            with psycopg.connect(dsn, autocommit=True, connect_timeout=10) as conn:
                conn.execute(PART)
                conn.execute("SELECT pgcolumnar.parallel_export_parquet("
                             f"'es_parbig'::regclass, 's3://{BUCKET}/cx', 4)").fetchall()
            out["result"] = "completed"
        except psycopg.Error as exc:
            out["result"] = str(exc)

    shutil.rmtree(bucket / "cx", ignore_errors=True)
    open(s3log, "w").close()
    bg = threading.Thread(target=run)
    bg.start()
    wrote = "no"
    for _ in range(300):
        n = _logn(s3log, r"^PUT /pgc-bucket/cx/part-")
        if isinstance(n, int) and n >= 1:
            wrote = "yes"
            break
        time.sleep(0.1)
    r["cx wrote"] = wrote
    # cancel only once all four workers' uploads are registered on the server; an upload
    # whose POST ?uploads is still in flight is #1743's window, not this check's
    cx_open = "0"
    for _ in range(300):
        cx_open = _open_uploads(bucket.parent, r"^pgc-bucket/cx/")
        if int(cx_open) >= 4:
            break
        time.sleep(0.1)
    r["cx all open"] = "yes" if int(cx_open) >= 4 else f"no ({cx_open} open)"
    with psycopg.connect(dsn, autocommit=True) as c:
        c.execute("SELECT pg_cancel_backend(pid) FROM pg_stat_activity "
                  "WHERE query LIKE '%parallel_export_parquet%' AND state = 'active' "
                  "AND pid <> pg_backend_pid()")
    bg.join(600)
    # let requests still in flight from the cancelled workers land (the log stops growing
    # for a second, at most 10 s), so a late write to a final key is read, not raced
    for _ in range(10):
        size = os.path.getsize(s3log)
        time.sleep(1)
        if os.path.getsize(s3log) == size:
            break
    res = out.get("result", "still running")
    r["cx cancelled"] = ("cancelled" if re.search(r"canceling statement|canceled on user request", res, re.I)
                         else "completed")
    n = _logn(s3log, r"^DELETE /pgc-bucket/cx/part-")
    r["cx delete"] = ("yes" if n >= 1 else "no") if isinstance(n, int) else n
    r["cx parts"] = str(_parts(bucket / "cx"))
    r["cx marker"] = "present" if (bucket / "cx" / "_SUCCESS").exists() else "absent"
    r["cx open"] = _open_uploads(bucket.parent, r"^pgc-bucket/cx/")


