"""The remote sink (#394 steps 3-4): the pytest twin of `test/objstore_sink_write.sh`,
every check by the shell's name (#1341).

Exports to s3:// go as one plain PUT below the part size and as a multipart upload above
it (create, parts, complete), and a failed export aborts its upload so nothing is ever
visible at the final key. parallel_export_parquet writes one object per worker under an
s3:// prefix, a _SUCCESS marker last, drops a smaller re-run's stale tail, and on cancel
removes what it wrote. The local SigV4 fixture server (test/objstore_http_server.py, the
shell's own) emulates multipart as S3 does: the object is the parts the complete LISTS,
each checked against its ETag, and it keeps the keys of the uploads still open in
`__open_uploads__`, the billable orphans.

EVERY OBJECT IS READ BACK and compared with the GENERATOR's rows, not with the columnar
table the export itself scanned, which would agree with a scan that bent rows. The Arrow
object is imported back from the bucket, so a count > 0 no longer passes a short object.

EACH REFUSAL IS ITS OWN GUARD'S: a part the server refuses (`__part_status__`) and a
complete that fails share 58030, so the part check is read by its own message, as are the
injected fault and the allow-list refusal. Abort is read from the server's open uploads,
not from the DELETE count alone, which passed an abort that named the wrong upload.

A PRIVATE CLUSTER, restarted with AWS_* in its environment, which the shared cluster
cannot do. The fixtures are generated by SQL; this module needs no pyarrow. The shell's
optional real-S3 arms are mirrored the way test_objstore_s3_read.py mirrors its own
(#432): they run when PGC_S3_INTEGRATION_ENDPOINT names a real S3 implementation, and
otherwise decline as UNMET_PRECONDITION, which expected_unrunnable.txt lists for every
major.
"""
